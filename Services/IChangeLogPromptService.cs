using System.Threading;
using System.Threading.Tasks;

namespace AvaloniaApp.Services;

/// <summary>
/// Use case: показать пользователю диалог подтверждения о добавлении строки
/// в Лист регистрации изменений (ЛРИ) и, при подтверждении, добавить её через
/// <see cref="IDocumentChangeEngine"/>.
///
/// Инкапсулирует логику, общую для двух точек входа:
///   1. Изменение пользователем полей <c>Revision</c> или <c>EffectiveDate</c>
///      в метаданных документа.
///   2. Нажатие кнопки «+» в редакторе ЛРИ на вкладке «Метаданные».
///
/// В обоих случаях пользователь должен явно подтвердить добавление строки
/// истории — это требование бизнес-процесса (ЛРИ фиксирует значимые изменения,
/// и каждая строка должна быть осознанной).
/// </summary>
public interface IChangeLogPromptService
{
    /// <summary>
    /// Показывает диалог подтверждения и, при согласии пользователя, добавляет
    /// новую строку в ЛРИ через <see cref="IDocumentChangeEngine.AddChangeLogRow"/>
    /// с автоинкрементом ревизии.
    ///
    /// Метод идемпотентен относительно одновременных вызовов: пока один
    /// диалог открыт, повторные вызовы (например, от автоматического
    /// отслеживания изменения метаданных) будут проигнорированы — семафор
    /// не пускает второй параллельный запрос.
    /// </summary>
    /// <param name="reason">Что изменилось (текст для пользователя в диалоге).</param>
    /// <param name="cancellationToken">Токен отмены ожидания.</param>
    Task PromptAndAddAsync(string reason, CancellationToken cancellationToken = default);
}
